"""Сквозная инфраструктура приложения.

Пакет намеренно отделён от `services/`:

  • `services/` — бизнес-логика (CAS, копирование, restore,
    системные интеграции). Знает о домене и не имеет права
    импортировать `ui.*` и `tkinter`.
  • `utils/` — инфраструктура без домена. Сейчас это только
    логирование, но именно сюда попадает всё, что нужно
    каждому слою и не тянет за собой моделей.

Почему не внутри `core/`: `core/paths.py` и
`core/settings_store.py` сами импортируют `utils.logger`.
Перенос логгера в `core` или `services` создал бы цикл
`core ↔ services` и сломал инвариант слоёв (`.zoorules` §4).

Почему отдельный пакет, а не один модуль: `utils.logger`
импортируют почти все модули проекта — во всех слоях. Пакет
честно обозначает эту роль и оставляет место для будущих
доменно-нейтральных помощников (форматирование, замеры времени).
"""
